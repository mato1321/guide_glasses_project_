package com.guideglasses.core.domain.text

/**
 * ASR 產出文字的正規化。
 *
 * 語音辨識的標點極不穩定 —— 同一句「停」可能回來是「停」「停。」「停，」，
 * 英文可能是全形也可能是半形、大寫也可能小寫。任何要拿 ASR 結果做片語比對的
 * 地方都必須先過這一關，否則會安靜地漏判。
 *
 * 抽成共用是因為現在有兩個地方需要它（快捷指令比對、翻譯目標語言解析），
 * 兩份實作若不同步就會出現「講同一句話在 A 有效在 B 無效」這種難查的問題。
 */
object SpokenText {

    /**
     * 去掉標點與空白、全形英數轉半形、英文轉小寫。
     *
     * 只保留字母與數字 —— 中文字本身是 letter，會被保留。
     */
    fun normalise(raw: String): String = buildString(raw.length) {
        for (ch in raw) {
            val c = when (ch) {
                // 全形英數轉半形（Ａ-Ｚ、ａ-ｚ、０-９ 與半形差 0xFEE0）
                in 'Ａ'..'Ｚ', in 'ａ'..'ｚ', in '０'..'９' ->
                    (ch.code - 0xFEE0).toChar()

                else -> ch
            }
            if (c.isLetterOrDigit()) append(c.lowercaseChar())
        }
    }

    /**
     * 給**片語比對**用的字串：正規化之後再把繁體摺成簡體。
     *
     * ### 為什麼需要
     *
     * 眼鏡上的離線辨識模型是 zh-CN 訓練的，說「前面有什麼」它回來的是
     * **「前面有什么」**。而本專案的指令片語全部寫成繁體，於是完全比對不到 ——
     * 實測使用者說了正確的指令，系統卻回「我還不會回答這種問題」。
     * 這種失敗特別難查：辨識明明是對的，看起來卻像功能壞掉。
     *
     * ### 為什麼是「繁 → 簡」而不是反過來
     *
     * 繁轉簡多半是**多對一**（後/后 → 后、裡/里 → 里），方向明確；
     * 簡轉繁則是一對多，需要看上下文才知道「后」該還原成「後」還是「后」，
     * 猜錯就會製造出新的比對失敗。這裡的輸出只拿來比對、不會給使用者看，
     * 所以往資訊量少的方向摺是安全的選擇。
     *
     * ### 為什麼不直接改 [normalise]
     *
     * `normalise` 的輸出在翻譯那條路徑上會**變成要翻譯的內容**
     * （見 `SpokenTranslation.extractText`），那是使用者聽得到的東西。
     * 比對用的摺疊不該汙染內容，所以分成兩個函式。
     *
     * 摺疊是逐字元的，**長度與 [normalise] 完全相同**，因此兩者的索引可以互換 ——
     * 需要「用摺疊過的字串找位置、用原字串取內容」時可以放心。
     */
    fun forMatching(raw: String): String = fold(normalise(raw))

    /**
     * 逐字把繁體摺成簡體。長度不變。
     *
     * ⚠️ **這不是通用的繁簡轉換器**，只涵蓋指令詞彙與日常用語。
     * 用途僅限片語比對；要拿來轉換給人看的文字請另外找完整的實作。
     */
    fun fold(text: String): String =
        if (text.none { it in VARIANTS }) text
        else buildString(text.length) {
            for (ch in text) append(VARIANTS[ch] ?: ch)
        }

    /**
     * 繁 → 簡對照。
     *
     * 刻意以短字串成組書寫並在建表時檢查長度 —— 兩行對不齊是這種表格
     * 最容易犯又最難發現的錯，寫成長長兩串幾乎不可能用眼睛校對。
     */
    private val VARIANTS: Map<Char, Char> = buildMap {
        fun add(traditional: String, simplified: String) {
            require(traditional.length == simplified.length) {
                "繁簡對照長度不符：$traditional / $simplified"
            }
            traditional.forEachIndexed { index, ch -> put(ch, simplified[index]) }
        }

        // 指令詞彙用得到的
        add("別說靜閉測試檢動", "别说静闭测试检动")
        add("沒羅盤機嗎張講複", "没罗盘机吗张讲复")
        add("覆剛麼聽唸門準備", "复刚么听念门准备")
        add("統狀態譯載語預臉", "统状态译载语预脸")
        add("單這個誰認識繼續", "单这个谁认识继续")
        add("讀頭車樓階號裡後", "读头车楼阶号里后")

        // 日常與導盲情境常見的
        add("幾給請開關過還們", "几给请开关过还们")
        add("為會來時間現點線", "为会来时间现点线")
        add("場邊東電話問題應", "场边东电话问题应")
        add("該對錯樣種買賣錢", "该对错样种买卖钱")
        add("業產圖書寫學習練", "业产图书写学习练")
        add("醫藥藍綠紅燈標誌", "医药蓝绿红灯标志")
        add("導視覺聲響記憶帶", "导视觉声响记忆带")
        add("幫隨離遠進選擇確", "帮随离远进选择确")
        add("決議論資訊網絡連", "决议论资讯网络连")
        add("斷傳輸據處執運轉", "断传输据处执运转")
        add("啟顯萬與稱參數變", "启显万与称参数变")
        add("換擊蹤豐飛餐館驗", "换击踪丰飞餐馆验")
        add("證輛輕鬆鐘鎖鐵長", "证辆轻松钟锁铁长")
        add("陽際雙雞難韓頁順", "阳际双鸡难韩页顺")
        add("風飯齊龍體聯廳廣", "风饭齐龙体联厅广")
    }
}

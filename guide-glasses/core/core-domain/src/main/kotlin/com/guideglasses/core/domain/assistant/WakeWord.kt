package com.guideglasses.core.domain.assistant

import com.guideglasses.core.domain.text.SpokenText

/**
 * 喚醒詞比對。
 *
 * 使用者不必先按按鈕 —— 說一聲就開始聽指令。對戴在頭上、
 * 看不到按鈕在哪的使用者，這是差別最大的一個互動改進。
 *
 * ### 為什麼需要這麼多變體
 *
 * 「盲狗」不是一般語料裡常見的詞，通用中文辨識模型很容易聽成同音或近音字
 * （忙狗、芒狗、盲購⋯）。只比對標準寫法的話，使用者會覺得
 * 「我明明喊了它卻沒反應」，而那在 log 裡看起來完全正常 —— 辨識有結果，
 * 只是不等於那四個字。
 *
 * 所以這裡收一組容錯寫法。真實裝置上還會聽到什麼，只能靠實測補 ——
 * `AssistantViewModel` 會把喚醒模式下聽到的每一句都記進 log，
 * 就是為了讓這份清單有依據可以長大。
 *
 * ### 誤觸的取捨
 *
 * 變體放得越寬，越容易被日常對話誤觸。所以刻意**不收單獨的「盲狗」** ——
 * 前面要有「呼叫」或「叫」，這樣「這隻導盲狗好可愛」不會把助理叫醒。
 */
object WakeWord {

    /** 標準說法。播報提示與文件都用這個。 */
    const val CANONICAL = "呼叫盲狗"

    /**
     * 比對規則：出現「叫」，其後兩個字以內出現「狗」或「犬」。
     *
     * ### 為什麼不逐字比對
     *
     * 第一版列了一堆變體（呼叫盲狗、呼叫忙狗、呼叫芒果⋯），眼鏡上實測**一句都沒中**：
     *
     * ```
     * 喚醒監聽聽到：「胡叫蒛狗」   呼 → 胡、盲 → 蒛
     * 喚醒監聽聽到：「呼叫狗」     盲 直接消失
     * 喚醒監聽聽到：「哭叫忙狗」   呼 → 哭、盲 → 忙
     * ```
     *
     * 模型把「呼」和「盲」**兩個字都聽壞了**，而那些變體全都假設「呼叫」是對的。
     * 逐字列舉在這種情況下永遠追不上 —— 每換一個人、換一次環境音就會冒出新寫法。
     *
     * 但三句都保住了同一個結構：**「叫」＋很短的距離＋「狗」**。
     * 那兩個音節都是清楚的塞音／爆破音，模型比較不會弄丟，
     * 中間那個「盲」則是最容易被吃掉或替換的。所以規則只鎖前後兩端。
     *
     * ### 誤觸的取捨
     *
     * 「這隻導盲狗好可愛」沒有「叫」，不會中。
     * 「他在叫狗」會中 —— 接受這個代價：誤觸的後果只是助理回一聲「我在」，
     * 而漏聽的後果是使用者對著沒反應的眼鏡重複喊，那顯然更糟。
     */
    private val PATTERN = Regex("叫.{0,2}[狗犬]")

    /**
     * 只靠「狗」認人時，句子最多幾個字。
     *
     * 第二版只看「叫…狗」，眼鏡上實測 8 次中 4 次 —— 因為**「叫」也不可靠**
     * （被聽成 照、啸）。真正穩的只有「狗」，8 次裡出現 7 次。
     *
     * 但只看「狗」會太鬆，所以加上長度限制。這個數字來自實測資料：
     * 喚醒嘗試都很短（叫狗、呼叫狗、胡照猛狗、呼叫盲狗，2–4 字），
     * 而誤收的環境語音都比較長且不含狗
     * （怎么走、因为现在不、是谢谢谢谢谢、家叫一个然后让这个）。
     */
    private const val SHORT_UTTERANCE_LIMIT = 5

    private val DOG = setOf('狗', '犬')

    /**
     * 這句話是不是在叫助理。
     *
     * 兩條規則取聯集：
     * 1. **「叫」＋兩字內＋「狗」** —— 長句子裡也認得出來
     *    （「欸呼叫盲狗幫我看前面」）。
     * 2. **很短且含「狗」** —— 「叫」被聽壞時的救援，
     *    靠「短」把日常對話擋在外面。
     *
     * @param utterance ASR 的原始輸出，不需要先正規化。
     */
    fun matches(utterance: String): Boolean {
        val folded = SpokenText.forMatching(utterance)
        if (folded.isEmpty()) return false

        if (PATTERN.containsMatchIn(folded)) return true
        return folded.length <= SHORT_UTTERANCE_LIMIT && folded.any { it in DOG }
    }
}

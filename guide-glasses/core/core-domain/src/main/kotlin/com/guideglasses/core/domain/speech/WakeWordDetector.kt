package com.guideglasses.core.domain.speech

import kotlinx.coroutines.flow.Flow

/**
 * 喚醒詞偵測。
 *
 * ### 為什麼不直接用語音辨識去比對字串
 *
 * 第一版是「一般辨識 → 把文字拿去比對片語」，實測命中率只有一半左右。
 * 原因是那個做法要求模型**先把整句話正確轉成文字**，而喚醒詞往往是
 * 罕見詞，被聽壞是常態：
 *
 * ```
 * 呼 → 胡、哭、不        叫 → 照、啸、（消失）
 * 盲 → 忙、芒、猛、蒛     狗 → 够、（消失）
 * ```
 *
 * 追著誤判去放寬比對規則是追不完的 —— 每換一個人、換一次環境音就有新寫法。
 *
 * 關鍵詞偵測是**專門為這件事訓練的模型**：它不轉文字，直接從聲音判斷
 * 「有沒有出現這個詞」。模型小很多（可以一直開著而不跟語音合成搶 CPU），
 * 對固定詞的辨識率也高得多。
 *
 * 這是「用對工具」而不是「把錯的工具調好」。
 */
interface WakeWordDetector {

    /** 模型是否可用。載入失敗或沒有麥克風權限時為 false。 */
    val isAvailable: Boolean

    /**
     * 持續監聽，每次偵測到喚醒詞就發出一個事件。
     *
     * @return 命中的喚醒詞（例如「呼叫盲狗」），供 log 判斷哪個說法最好用。
     */
    fun detections(): Flow<String>

    fun shutdown()
}
